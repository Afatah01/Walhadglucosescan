-- Walhad Glucose Scan — the table that counts AI questions.
--
-- It exists for one reason: so that one install cannot run up the bill.
-- Nothing about the person is stored. The install id is a hash, no glucose
-- value, no question and no answer is ever written down.

create table if not exists public.ai_usage (
  id          bigint generated by default as identity primary key,
  -- a hash of the install id, never the id itself
  install_id  text        not null,
  -- the day in UTC, so that the limit resets at the same moment for everybody
  day         date        not null,
  calls       integer     not null default 0,
  updated_at  timestamptz not null default now(),
  unique (install_id, day)
);

-- Only this table's owner (the Edge Function, which uses the service role)
-- may read or write it.
alter table public.ai_usage enable row level security;

-- No policies on purpose: row level security with no policy blocks every
-- request made with the public anon key, which is exactly what we want. The
-- function bypasses it with the service role key, which is never shipped.

